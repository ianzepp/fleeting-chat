// Acceptance test (spec §9) with three independent MCP sessions. Usage: MCP_URL=http://localhost:8799/mcp node test/e2e.mjs
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";
const URL_ = new URL(process.env.MCP_URL ?? "http://localhost:8799/mcp");
const mk = async () => { const c = new Client({ name: "e2e", version: "1" }); await c.connect(new StreamableHTTPClientTransport(URL_)); return c; };
const call = async (c, name, args = {}) => {
  const r = await c.callTool({ name, arguments: args }, undefined, { timeout: 60000 });
  const j = JSON.parse(r.content.find((x) => x.type === "text").text);
  return r.isError ? { __err: j } : j;
};
let fails = 0; const ok = (cond, msg) => { console.log(`${cond ? "PASS" : "FAIL"} ${msg}`); if (!cond) fails++; };
const A = await mk(), B = await mk(), C = await mk();
const tools = (await A.listTools()).tools.map((t) => t.name).sort();
ok(tools.length === 12, `tools/list → ${tools.join(",")}`);
const cr = await call(A, "create_channel", { nick: "alice", ttl_seconds: 3600 });
if (!cr.channel_id) { console.log("create err", JSON.stringify(cr)); process.exit(1); }
ok(cr.seat === "1" && /^\d{3}-\d{3}-\d{3}$/.test(cr.channel_id), `create ${cr.channel_id}`);
const id = cr.channel_id, raw = id.replace(/-/g, "");
const jb = await call(B, "join_channel", { channel_id: raw, nick: "bob" });
ok(jb.seat === "2" && jb.history.length === 0, `B join seat ${jb.seat}`);
const pB = call(B, "poll_messages", { channel_id: id, wait_seconds: 20 });
await new Promise((r) => setTimeout(r, 500)); const t0 = Date.now();
await call(A, "send_message", { channel_id: id, body: "ping" });
const gotB = await pB;
ok(gotB.messages.length === 1 && gotB.messages[0].body === "ping" && gotB.messages[0].nick === "alice" && Date.now() - t0 < 3000, `B long-poll got ping in ${Date.now() - t0}ms`);
await call(B, "send_message", { channel_id: id, body: "pong" });
const gotA = await call(A, "poll_messages", { channel_id: id, wait_seconds: 5 });
ok(gotA.messages.length === 1 && gotA.messages[0].body === "pong", "A got only pong (own filtered)");
ok((await call(A, "poll_messages", { channel_id: id, wait_seconds: 0 })).messages.length === 0, "cursor advanced");
ok((await call(C, "join_channel", { channel_id: id })).__err?.error === "channel_full", "C channel_full");
ok((await call(A, "expand_channel", { channel_id: id, expand_by: 1 })).max_seats === 3, "expand → 3");
ok((await call(C, "join_channel", { channel_id: id })).seat === "3", "C joins seat 3");
const rj = await call(A, "join_channel", { channel_id: id });
ok(rj.rejoined === true && rj.seat === "1", "A re-bind same seat (signed proof)");
ok(!(await call(A, "send_message", { channel_id: id, body: "after rebind" })).__err, "send after rebind");
const ex = await call(A, "extend_channel", { channel_id: id, extend_by_seconds: 3600 });
ok(Date.parse(ex.absolute_expires_at) > Date.parse(cr.absolute_expires_at), "extend moved expiry");
const info = await call(A, "channel_info", { channel_id: id });
ok(info.joined && info.seat === "1", "channel_info");
const ics = "BEGIN:VCALENDAR\nEND:VCALENDAR\n", b64 = Buffer.from(ics).toString("base64");
const up = await call(A, "upload_file", { channel_id: id, filename: "x.ics", content_type: "text/calendar", content_base64: b64 });
ok(!!up.file_id, `upload ${up.file_id}`);
const dl = await call(B, "download_file", { channel_id: id, file_id: up.file_id });
ok(dl.content_base64 === b64 && dl.text === ics, "download identical + text");
const lc = await call(A, "list_channels");
ok(lc.channels.length === 1, "list_channels has 1");
const all = JSON.stringify([cr, jb, rj, info, lc, up, dl]);
ok(!/PRIVATE KEY|"token"/.test(all), "no private key / bearer in tool output");
ok((await call(A, "leave_channel", { channel_id: id, farewell: "bye" })).left, "leave");
ok((await call(A, "list_channels")).channels.length === 0, "list empty after leave");
ok((await call(A, "send_message", { channel_id: id, body: "x" })).__err?.error === "not_joined", "not_joined after leave");
const rs = await call(C, "reserve_channel", {});
ok(!!rs.channel_id && rs.share_url.includes(rs.channel_id), "reserve");
console.log(fails ? `${fails} FAILED` : "ALL PASS"); process.exit(fails ? 1 : 0);
